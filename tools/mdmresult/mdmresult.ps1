<#
.SYNOPSIS
    mdmresult - gpresult-style policy report for Group Policy, Intune/MDM and co-managed devices.
.DESCRIPTION
    Runs PolicyPilot's device scan without the GUI and writes the same HTML report as
    PolicyPilot's "Export HTML": ADMX/CSP names, CSP gap analysis, conflicts, apps and
    compliance. Self-contained: needs only admx_metadata.json and csp_metadata.json
    next to this script.
.PARAMETER Mode
    Local    - Group Policy result (gpresult /x) with ADMX enrichment.
    Intune   - local MDM policy state (PolicyManager, MDM diagnostics, IME).
    Combined - both; use for hybrid joined / co-managed devices. Default.
.PARAMETER Path
    HTML output file. Default: .\mdmresult_<COMPUTERNAME>_<timestamp>.html
.PARAMETER JsonPath
    Also write a machine-readable JSON summary (settings, conflicts, apps, local health) to this file.
.PARAMETER IncludeNotConfigured
    Add the catalogue of known Policy CSP settings that are not configured (about 1,600 rows).
.PARAMETER Force
    Overwrite existing output files.
.PARAMETER Open
    Open the report when finished.
.EXAMPLE
    .\mdmresult.ps1
.EXAMPLE
    .\mdmresult.ps1 -Mode Intune -Path C:\Temp\policy.html -JsonPath C:\Temp\policy.json -Force -Open
.OUTPUTS
    Exit code 0 = report written, nothing to review; 2 = report written with findings (conflicts,
    local health warnings or issues, failed apps, or a failed Group Policy part); 1 = error.
.NOTES
    Run elevated: computer-scope gpresult and Win32 app state need administrator rights.
    GENERATED by build\Build-MdmResult.ps1 from PolicyPilot.ps1 0.1.0 (SHA256 BDAB0DAFEB337E8D).
    Do not edit mdmresult.ps1; edit build\mdmresult.template.ps1 and rebuild.
#>
