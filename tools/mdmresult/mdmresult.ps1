                    $rawGPOs = [System.Collections.Generic.List[object]]::new()
                    $resolvedGuids = [System.Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
                    foreach ($entry in $ouLdapResults) {
